FIXTURES = Path(__file__).resolve().parents[2] / 'fixtures' / 'synthetic' / 'remote_delay'


@pytest.fixture
def store(tmp_path):
    result = CaseStore(tmp_path / 'regression.db')
    yield result
    result.close()


def setup_case(store, sparse=False):
    case = store.create_case(machine_id='EX1', title='SYNTHETIC regression', actor='Engineer', synthetic=True,
                             symptom_start='2026-03-04T09:06:00Z', symptom_end='2026-03-04T09:07:30Z', symptom_source='synthetic')
    profile = parse_profile(json.loads((FIXTURES / 'synthetic_console_profile.json').read_text()))
    raw = (b'time,machine,metric,reading,units,path,cmd_id\n'
           b'2026-03-04T09:00:00Z,EX1,lte_rtt,42,ms,probe,\n'
           b'2026-03-04T10:00:00Z,EX1,lte_rtt,43,ms,probe,\n') if sparse else (FIXTURES / 'synthetic_ex1_console.csv').read_bytes()
    imported, _ = store.commit_import(case['id'], raw, 'synthetic.csv', profile, actor='Engineer')
    run = store.investigate(case['id'], actor='Engineer')
    return case['id'], imported['id'], run


def approve(store, cid, run):
    return store.append(cid, 'check_review', {'run_id': run['id'], 'check_id': 'CHK-SOURCE-ROWS',
                        'verdict': 'accepted', 'reason': 'Review actual source rows'}, actor='Engineer', source='synthetic://review')


def test_public_append_cannot_forge_tool_receipts_or_investigations(store):
    cid, _, run = setup_case(store)
    approve(store, cid, run)
    before = len(store.ledger(cid))
    with pytest.raises(LedgerError, match='only be generated by the engine'):
        store.append(cid, 'check_execution', {'run_id': run['id'], 'check_id': 'CHK-SOURCE-ROWS',
                     'status': 'automatic_read_only', 'tool_result': {'tool': 'invented', 'count': 999999}}, actor='Engineer')
    with pytest.raises(LedgerError, match='only be generated by the engine'):
        store.append(cid, 'investigation_run', {}, actor='Engineer')
    assert len(store.ledger(cid)) == before
    actual = store.execute_automatic(cid, 'CHK-SOURCE-ROWS', actor='Engineer')
    receipt = actual['entry']['payload']['tool_result']
    assert receipt['count'] == actual['result']['count'] > 0
    assert receipt['digest'] == hashlib.sha256(json.dumps(actual['result'], sort_keys=True, default=str).encode()).hexdigest()
    assert receipt['input_hashes'] == run['input_hashes']
    assert store.verify(cid)['ledger_chain']['valid']


def test_unauthorized_and_stale_checks_do_not_run_tools(store, monkeypatch):
    cid, _, run = setup_case(store)
    called = []
    monkeypatch.setattr(engine, 'window_rows', lambda *_: called.append(True))
    with pytest.raises(LedgerError, match='Accept or edit'):
        store.execute_automatic(cid, 'CHK-SOURCE-ROWS', actor='Engineer')
    approve(store, cid, run)
    store.assert_context({'machine_id': 'EX1', 'key': 'site', 'value': 'Synthetic site', 'status': 'reported',
                          'source': 'synthetic://site', 'actor': 'Engineer', 'effective_from': '2026-03-01T00:00:00Z'})
    with pytest.raises(LedgerError, match='stale'):
        store.execute_automatic(cid, 'CHK-SOURCE-ROWS', actor='Engineer')
    assert called == []


def test_gap_window_is_not_evidence_and_rejection_rolls_back(store):
    cid, import_id, run = setup_case(store, sparse=True)
    decision = store.append(cid, 'decision', {'run_id': run['id'], 'options_considered': ['inspect'],
                            'chosen_option': 'inspect', 'rationale': 'Synthetic inspection'}, actor='Engineer')
    action = store.append(cid, 'action', {'decision_id': decision['id'], 'action_type': 'onsite_inspection',
                          'description': 'Synthetic action', 'status': 'simulated', 'performed_at': '2026-03-04T09:10:00Z',
                          'performer': 'Engineer'}, actor='Engineer')
    outcome = {'action_id': action['id'], 'result': 'recovered', 'observed_from': '2026-03-04T09:30:00Z',
               'observed_to': '2026-03-04T09:31:00Z', 'verification': 'evidence_attached',
               'evidence': [import_id], 'observations': 'Synthetic report'}
    before = len(store.ledger(cid))
    with pytest.raises(LedgerError, match='has records inside'):
        store.append(cid, 'outcome', outcome, actor='Engineer')
    assert not store.db.in_transaction and len(store.ledger(cid)) == before
    # The same import really does contain a sample in this later window.
    accepted = store.append(cid, 'outcome', {**outcome, 'observed_from': '2026-03-04T09:59:00Z',
                            'observed_to': '2026-03-04T10:00:00Z'}, actor='Engineer')
    assert accepted['payload']['verification_grade'] == 'engineer_reported_not_independently_reviewed'
    assert accepted['payload']['simulated'] is True


def test_concurrent_connections_preserve_one_complete_hash_chain(tmp_path):
    path = tmp_path / 'concurrent.db'
    initial = CaseStore(path)
    cid = initial.create_case(machine_id='EX1', title='SYNTHETIC concurrency', actor='Engineer', synthetic=True)['id']
    initial.close()
    start = threading.Barrier(2)
    heads_read = threading.Barrier(2)

    def worker(actor):
        connection = CaseStore(path)
        original = connection.ledger
        def widen_race(case_id):
            entries = original(case_id)
            # Old code lets both connections read the same head. Serialized code lets
            # only one reach here, so this short bounded barrier expires safely.
            try:
                heads_read.wait(timeout=.2)
            except threading.BrokenBarrierError:
                pass
            return entries
        connection.ledger = widen_race
        try:
            start.wait(timeout=5)
            return connection.append(cid, 'support_milestone', {'milestone': 'issue_reported',
                                     'observed_at': '2026-03-04T09:00:00Z'}, actor=actor)['id']
        finally:
            connection.close()

    with ThreadPoolExecutor(max_workers=2) as pool:
        ids = list(pool.map(worker, ['Engineer A', 'Engineer B']))
    result = CaseStore(path)
    try:
        assert len(set(ids)) == 2
        assert len(result.ledger(cid)) == 3
        assert result.verify(cid)['ledger_chain']['valid']
    finally:
        result.close()


def test_failed_run_receipt_rolls_back_run_insert(store, monkeypatch):
    cid, _, _ = setup_case(store)
    previous = len(store.runs(cid))
    def reject(*args, **kwargs):
        raise LedgerError('Synthetic ledger failure')
    monkeypatch.setattr(store, '_append_locked', reject)
    with pytest.raises(LedgerError, match='Synthetic ledger failure'):
        store.investigate(cid, actor='Engineer')
    assert not store.db.in_transaction and len(store.runs(cid)) == previous
